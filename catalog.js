function catOf(name) {
  const n = name.toLowerCase();
  if (n.startsWith("роза")) return "roses";
  if (GARDEN_WORDS.some(w => n.includes(w))) return "garden";
  if (ACCENT_WORDS.some(w => n.includes(w))) return "accents";
  return "exotic";
}
